function enrichFile(filePath, enrichedMap) {
  if (!fs.existsSync(filePath)) {
    console.log("File not found:", filePath);
    return;
  }
  const content = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  let count = 0;
  for (const q of content) {
    const num = q.question_number || q.number;
    if (enrichedMap[num]) {
      const expBody = enrichedMap[num];
      q.explanation = expBody;
      q.explanation_html = `<div class="p-4 bg-emerald-50 dark:bg-emerald-950/40 rounded-xl border border-emerald-200 dark:border-emerald-800/60 text-emerald-900 dark:text-emerald-100 text-sm space-y-2"><div class="leading-relaxed text-slate-700 dark:text-slate-200">${expBody.replace(/\\n/g, '<br/>')}</div></div>`;
      count++;
    }
  }
  fs.writeFileSync(filePath, JSON.stringify(content, null, 2), 'utf8');
  console.log(`Enriched ${count} questions in ${filePath}`);
}

