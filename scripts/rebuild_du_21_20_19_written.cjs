function saveSession(sessionCode, title, questions, publicFileName, repoFileName) {
  const payload = {
    schema_version: '2.0',
    university: 'DU',
    session: sessionCode,
    title,
    exam_type: 'Written',
    total_questions: questions.length,
    questions,
  };

  const jsonStr = JSON.stringify(payload, null, 2);
  const publicPath = path.join(__dirname, '..', 'public', 'assets', 'aistudio', publicFileName);
  const repoDir = path.join(__dirname, '..', 'Question', 'DU');
  const repoPath = path.join(repoDir, repoFileName);

  fs.mkdirSync(path.dirname(publicPath), { recursive: true });
  fs.mkdirSync(repoDir, { recursive: true });

  fs.writeFileSync(publicPath, jsonStr, 'utf8');
  fs.writeFileSync(repoPath, jsonStr, 'utf8');
  console.log(`Saved ${title} (${questions.length} questions) -> ${publicFileName} & ${repoFileName}`);
}

