function buildQuestion(idx, subject, questionText, explanationText, qImages = [], expImages = []) {
  const htmlParagraphs = questionText
    .split('\n')
    .map((line) => {
      const imgMatch = line.match(/^!\[([^\]]*)\]\(([^)]+)\)$/);
      if (imgMatch) {
        return `<p><img src="${imgMatch[2]}" alt="${imgMatch[1]}" /></p>`;
      }
      return `<p>${line}</p>`;
    })
    .join('');

  return {
    number: idx,
    question_number: idx,
    subject,
    question: questionText,
    question_html: htmlParagraphs,
    question_image_urls: qImages,
    options: [],
    raw_options: [],
    correct_answer: null,
    answer_detection: 'written_question_no_mcq_answer',
    explanation: explanationText,
    explanation_html: null,
    explanation_image_urls: expImages,
  };
}

