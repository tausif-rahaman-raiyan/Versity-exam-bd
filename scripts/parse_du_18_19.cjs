function parseRawTextToQuestions(text) {
  const lines = text.split('\n');
  const questions = [];
  let currentSub = '';
  let subCount = 0;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    const subMatch = line.match(/^\[([^\]]+)\]\s*(\d+)\.\s*(.*)/);
    if (subMatch) {
      const rawSub = subMatch[1].replace(/\(\d+\)/g, '').trim();
      const numStr = subMatch[2];
      const qText = subMatch[3].trim();

      let subject = rawSub;
      if (rawSub.includes('বাংলা')) subject = 'Bangla';
      else if (rawSub.includes('জীববিজ্ঞান')) subject = 'Biology';
      else if (rawSub.includes('English')) subject = 'English';
      else if (rawSub.includes('রসায়ন')) subject = 'Chemistry';
      else if (rawSub.includes('পদার্থবিজ্ঞান')) subject = 'Physics';
      else if (rawSub.includes('উচ্চতর গণিত')) subject = 'Mathematics';

      if (subject !== currentSub) {
        currentSub = subject;
        subCount = 0;
      }
      subCount++;

      // Next line should be options
      let optLine = lines[i + 1] ? lines[i + 1].trim() : '';
      let options = [];
      if (optLine.startsWith('A:')) {
        i++; // consume option line
        const parts = optLine.split(/\|\s*/);
        options = parts.map(p => p.replace(/^[A-D]:\s*/, '').trim());
      }

      const keyPrefix = subject === 'Bangla' ? 'bn_' :
                        subject === 'Biology' ? 'bio_' :
                        subject === 'English' ? 'eng_' :
                        subject === 'Chemistry' ? 'chem_' :
                        subject === 'Physics' ? 'phy_' : 'math_';

      const expKey = keyPrefix + subCount;
      const expObj = du1819Explanations[expKey] || {
        answer: 0,
        exp: "সঠিক উত্তর ও সমাধান প্রস্তুত করা হচ্ছে।"
      };

      questions.push({
        id: "du-18-19-q" + questions.length,
        number: questions.length + 1,
        subject: subject,
        question: qText,
        options: options,
        correct_answer: expObj.answer,
        explanation: expObj.exp,
        marks: 1
      });
    }
  }
  return questions;
}

